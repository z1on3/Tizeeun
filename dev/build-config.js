// Build step: copy the TMDB credentials from .env into app/js/config.js.
//
// The app is plain, unbundled JS, so nothing loads .env at runtime. Instead the
// catalog key is baked into config.js (shipped with the app), matching the
// documented model ("the catalog key is built in: set tmdbKey in config.js").
//
// Run:  node dev/build-config.js
//   - TMDB_READ_TOKEN  (v4 read access token, preferred — used as a Bearer header)
//   - TMDB_API_KEY     (v3 API key, fallback — sent as a query param)
//   - TMDB_BASE        (optional — override the API base URL, e.g. a proxy)
//
// If no key is present it fails with a clear message rather than writing a
// config that silently disables the catalog.
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const ENV_FILE = path.join(ROOT, '.env');
const OUT_FILE = path.join(ROOT, 'app', 'js', 'config.js');

function parseEnv(file) {
  const raw = fs.readFileSync(file, 'utf8');
  const env = {};
  raw.split(/\r?\n/).forEach((line) => {
    let l = line.trim();
    if (!l || l[0] === '#') return;
    const i = l.indexOf('=');
    if (i < 0) return;
    const k = l.slice(0, i).trim();
    let v = l.slice(i + 1).trim();
    if ((v[0] === '"' || v[0] === "'") && v.slice(-1) === v[0]) v = v.slice(1, -1);
    env[k] = v;
  });
  return env;
}

const env = fs.existsSync(ENV_FILE) ? parseEnv(ENV_FILE) : {};
const base = env.TMDB_BASE || 'https://api.themoviedb.org/3';

// Prefer the v4 read access token; fall back to the v3 API key. The app tells
// them apart by length (v4 tokens are longer), so either works once embedded.
const readToken = env.TMDB_READ_TOKEN || '';
const apiKey = env.TMDB_API_KEY || '';
const key = readToken || apiKey;
const which = readToken ? 'v4 read access token (TMDB_READ_TOKEN)' : 'v3 API key (TMDB_API_KEY)';

if (!key) {
  // Lenient so `npm run dev` still starts: the app just runs with the catalog
  // disabled ("not available in this build"). Set CONFIG_STRICT=1 to fail instead.
  if (process.env.CONFIG_STRICT) {
    console.error('No TMDB key found in ' + ENV_FILE + '.');
    console.error('Set TMDB_READ_TOKEN (v4) or TMDB_API_KEY (v3).');
    process.exit(1);
  }
  console.log('No TMDB key in ' + path.relative(ROOT, ENV_FILE) + ' — leaving ' + path.relative(ROOT, OUT_FILE) + ' unchanged.');
  console.log('Catalog will run in "not available" mode until a key is added.');
  process.exit(0);
}

const out = [
  '// Build-time configuration, shipped with the app.',
  '// NOTE: anything here is public — the npm package and the TV can be inspected.',
  '// Generated by `node dev/build-config.js` from ' + path.relative(ROOT, ENV_FILE) + '. Re-run it after changing .env.',
  'var Config = {',
  '  tmdbKey: ' + JSON.stringify(key) + ',   // ' + which,
  '  tmdbBase: ' + JSON.stringify(base) + ' // or your proxy, e.g. https://tmdb.example.workers.dev/3',
  '};',
  ''
].join('\n');

fs.writeFileSync(OUT_FILE, out);
console.log('Wrote ' + path.relative(ROOT, OUT_FILE));
console.log('  key:    ' + which);
console.log('  base:   ' + base);
console.log('  length: ' + key.length + ' chars');
